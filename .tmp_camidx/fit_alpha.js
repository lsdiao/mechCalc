// 精确拟合：alpha = am*(2π/S)*(360n/(60θh))² ?
const cases = [
  // [S, θh, n, alpha_server]
  [2, 90, 1000, 77213.366],
  [3, 180, 400, 2059.023],
  [2, 90, 10, 7.721],
  [6, 270, 80, 18.302],
  [6, 270, 90, 23.164],
  [6, 270, 100, 28.598],
  [6, 180, 80, 41.18],
  [6, 360, 80, 10.295],
  [5, 270, 80, 21.963],
  [4, 270, 80, 27.454],
  [8, 270, 80, 13.727],
  [6, 90, 80, 164.722],
  [2, 270, 80, 54.907],
  [6, 270, 81, 18.763],
  [6, 269, 80, 18.439],
  [12, 270, 80, 9.151],
  [100, 270, 80, 1.098],
];
const am = 5.53;
for (const [S, th, n, a] of cases) {
  const X = (2 * Math.PI / S) * Math.pow(360 * n / (60 * th), 2);
  const pred = am * X;
  console.log(`S=${S} θh=${th} n=${n} server=${a} pred=${pred.toFixed(6)} diff=${(a - pred).toFixed(6)} rel=${((a - pred) / pred).toExponential(3)} am_eff=${(a / X).toFixed(7)}`);
}
