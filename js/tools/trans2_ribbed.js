  /* 计算有效带长 Le0（用小轮/大轮有效直径 de，经 API 实测验证） */
  function calBeltLen(de1, de2, a0) {
    return 2 * a0 + PI / 2 * (de1 + de2) + Math.pow(de2 - de1, 2) / (4 * a0);
  }
  /* 小带轮包角 α1（°） */
  function alpha1Cal(de1, de2, a) {
    return 180 - (de2 - de1) / a * 57.3;
  }
  /* 实际中心距 a = a0 + (Le - Le0)/2；α1 与系数由选定带长反算 */
  function geoCalc(type, de1, de2, a0, calLe) {
    var le = nearest(LE_STD[type], calLe);
    var a = a0 + (le - calLe) / 2;
    var a1 = alpha1Cal(de1, de2, a);
    var kA = kAlphaQuery(r2(a1));
    if (kA === null) return null;
    return { Le: le, a: r2(a), alpha1: r2(a1), kAlpha: kA, kL: kLQuery(type, le), kr: krQuery(a1), deltaMin: adjDelta(type, le), calLe: r2(calLe) };
  }
  function adjDelta(type, le) {
    var rows = ADJ[type] || [];
    for (var i = 0; i < rows.length; i++) if (le <= rows[i][0]) return rows[i];
    return rows.length ? rows[rows.length - 1] : null;
  }

  /* 楔数计算与圆整 */
  function wedgeCount(Pd, p1, dp1, kA, kL, kr) {
    if (!(p1 > 0) || !(kr > 0)) return null;
    return Pd / ((p1 + dp1) * kA * kL * kr);
  }
  function wedgeStd(type, z) {
    var series = WEDGE_STD[type] || [];
    for (var i = 0; i < series.length; i++) if (series[i] >= z * 0.9999) return series[i];
    return series.length ? series[series.length - 1] : null;
  }

  /* ---------- 力计算（与原站 polyv2 实测一致） ----------
   * Ft = 1000·Pd/v
   * F0(总初拉力) = (Ft/2)·(1 + 2/(kr−1))；单楔 F0' = F0/z
   * F1 = Ft/2 + F0；F2 = F1 − Ft；FQ = 2·F0·sin(α1/2) */
  function forces(Pd, v, z, kr, alpha1) {
    var Ft = 1000 * Pd / v;
    var F0 = (Ft / 2) * (1 + 2 / (kr - 1));
    var F1 = Ft / 2 + F0;
    var F2 = F1 - Ft;
    var FQ = 2 * F0 * Math.sin(alpha1 / 2 * PI / 180);
    return { Ft: Ft, F0z: F0 / z, F0: F0, F1: F1, F2: F2, FQ: FQ };
  }

